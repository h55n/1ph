def get_headers(impersonate: str = "chrome120") -> dict[str, str]:
    """Return the full, ordered header set for the given browser profile."""
    profile = HEADER_PROFILES.get(impersonate)
    if not profile:
        profile = HEADER_PROFILES["chrome120"]
    return dict(profile)


def get_random_profile_name(
    exclude: Optional[list[str]] = None,
    desktop_only: bool = True,
) -> str:
    """Pick a random browser profile name (session-level rotation)."""
    candidates = list(HEADER_PROFILES.keys())
    if desktop_only:
        # Exclude mobile profiles for desktop-targeted sites
        candidates = [c for c in candidates if "116" not in c and "safari16" not in c]
    if exclude:
        candidates = [c for c in candidates if c not in exclude]
    return random.choice(candidates) if candidates else "chrome120"
